namespace Motely;

public static class MotelySeedKeywordSequences
{
    public static IEnumerable<string> RepeatCharKeywords(int repeatCount)
    {
        for (int c = (int)'A'; c <= (int)'Z'; c++)
            yield return new string((char)c, repeatCount);
    }

    public static IEnumerable<string> AscendingDigitLetterKeywords(int length)
    {
        const string chars = "123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ";
        int maxStart = chars.Length - length;
        for (int i = 0; i <= maxStart; i++)
            yield return chars.Substring(i, length);
    }

    public static IEnumerable<string> DescendingDigitLetterKeywords(int length)
    {
        const string chars = "ZYXWVUTSRQPONMLKJIHGFEDCBA987654321";
        int maxStart = chars.Length - length;
        for (int i = 0; i <= maxStart; i++)
            yield return chars.Substring(i, length);
    }

    public static IEnumerable<string> MirrorPatternKeywords(int length)
    {
        const string symmetricChars = "AHIMOTUVWXY18";

        IEnumerable<string> Generate(string current, int remaining)
        {
            if (remaining == 0)
            {
                yield return current;
                yield break;
            }

            foreach (char c in symmetricChars)
            {
                foreach (string pattern in Generate(current + c, remaining - 1))
                    yield return pattern;
            }
        }

        foreach (string pattern in Generate("", length))
            yield return pattern;
    }

    public const long GrossKeywordAestheticSeedCount = 307_252_260L;
    public const long FunnyKeywordAestheticSeedCount = 493_728_588L;
    public const long BalatroKeywordAestheticSeedCount = 913_677_733L;
    public const long LeetKeywordAestheticSeedCount = 1_525_175_581L;
    public const long NsfwKeywordAestheticSeedCount = 302_944_676L;

    public static IEnumerable<string> EnumerateAestheticSeeds(
        JamlAesthetic aesthetic,
        char[]? paddingAlphabet = null
    )
    {
        foreach (
            var seed in MotelyGlobals.GeneratePaddedSeedsForKeywords(
                KeywordsFor(aesthetic),
                paddingAlphabet
            )
        )
            yield return seed;
    }

    public static long GetAestheticSeedCount(
        JamlAesthetic aesthetic,
        char[]? paddingAlphabet = null
    )
    {
        if (paddingAlphabet is { Length: > 0 })
            return MotelyGlobals.GetPaddedSeedCountForKeywordsLong(
                KeywordsFor(aesthetic),
                paddingAlphabet
            );

        return aesthetic switch
        {
            JamlAesthetic.Gross => GrossKeywordAestheticSeedCount,
            JamlAesthetic.Funny => FunnyKeywordAestheticSeedCount,
            JamlAesthetic.Balatro => BalatroKeywordAestheticSeedCount,
            JamlAesthetic.Leet => LeetKeywordAestheticSeedCount,
            JamlAesthetic.Nsfw => NsfwKeywordAestheticSeedCount,
            _ => throw new ArgumentOutOfRangeException(
                nameof(aesthetic),
                aesthetic,
                "Not a keyword aesthetic."
            ),
        };
    }

