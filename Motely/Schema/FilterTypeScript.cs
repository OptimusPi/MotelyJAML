using System.Text;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;

namespace Motely.Schema;

/// <summary>
/// TypeScript declarations for a filter document, read off <see cref="FilterJsonSchema"/>: the
/// same keys, the same nesting, the same enum names, so a TypeScript app holds a filter as a plain
/// <c>JamlFilter</c> object and hands <c>JSON.stringify(filter)</c> to the loader — no parser and
/// no key list of its own. Enum types are the canonical names only; the loader also takes any
/// casing, which a type deliberately does not invite, and refuses a number.
/// </summary>
public static partial class FilterTypeScript
{
    /// <summary>The declarations, ready to write to disk.</summary>
    public static string Generate() => Emit(FilterJsonSchema.Build());

    /// <summary>The declarations for a schema shaped like <see cref="FilterJsonSchema.Build"/>.</summary>
    public static string Emit(JsonObject schema)
    {
        var defs = (JsonObject)schema["definitions"]!;
        var sb = new StringBuilder();
        sb.Append(
            "// Generated by `motely schema` from the engine's own clause types (Motely/Schema/FilterTypeScript.cs).\n"
                + "// Do not edit; regenerate. A filter is plain JSON: build a JamlFilter, hand JSON.stringify(filter)\n"
                + "// to JamlConfigLoader.check or fromJaml, and read one back with JSON.parse.\n\n"
        );

        foreach (var (name, node) in (JsonObject)defs["enums"]!)
            sb.Append("export type ").Append(EnumTypeName(name)).Append(" = ").Append(EnumUnion(node!)).Append(";\n");
        sb.Append('\n');

        sb.Append("/** A whole filter document, as the engine loads it from YAML or JSON. */\n");
        sb.Append("export interface JamlFilter ").Append(ObjectBody(schema)).Append("\n\n");

        foreach (var (name, node) in defs)
        {
            if (name == "enums")
                continue;
            if (node is JsonObject { } o && o["properties"] is JsonObject)
                sb.Append("export interface ").Append(DefTypeName(name)).Append(' ').Append(ObjectBody(o)).Append("\n\n");
            else
                sb.Append("export type ").Append(DefTypeName(name)).Append(" = ").Append(Type(node!)).Append(";\n\n");
        }

        return sb.ToString().TrimEnd('\n') + "\n";
    }

    /// <summary><c>MotelyJoker</c> → <c>MotelyJokerName</c>: the enum's names, not its runtime values.</summary>
    private static string EnumTypeName(string enumName) => enumName + "Name";

    /// <summary><c>jokerClause</c> → <c>JamlJokerClause</c>; the clause union is <c>JamlClause</c>.</summary>
    private static string DefTypeName(string defName) =>
        "Jaml" + char.ToUpperInvariant(defName[0]) + defName[1..];

    private static string RefName(string pointer)
    {
        const string Enums = "#/definitions/enums/";
        const string Defs = "#/definitions/";
        if (pointer.StartsWith(Enums, StringComparison.Ordinal))
            return EnumTypeName(pointer[Enums.Length..]);
        if (pointer.StartsWith(Defs, StringComparison.Ordinal))
            return DefTypeName(pointer[Defs.Length..]);
        throw new InvalidOperationException($"Unexpected schema reference {pointer}.");
    }

    /// <summary>An enum definition is <c>anyOf [names, case-insensitive pattern, integer]</c>; only the names become the type.</summary>
    private static string EnumUnion(JsonNode node)
    {
        foreach (var alternative in (JsonArray)node["anyOf"]!)
            if (alternative?["enum"] is JsonArray names)
                return Union(names.Select(n => Literal(n!.GetValue<string>())));
        throw new InvalidOperationException("An enum definition has no name list.");
    }

    private static string Type(JsonNode node)
    {
        if (node is not JsonObject o || o.Count == 0)
            return "unknown";
        if (o["$ref"] is JsonValue reference)
            return RefName(reference.GetValue<string>());
        if (o["anyOf"] is JsonArray anyOf)
            return Union(anyOf.Select(n => Type(n!)));
        if (o["allOf"] is JsonArray allOf)
            return AllOf(allOf);
        if (o["enum"] is JsonArray values)
            return Union(values.Select(v => Literal(v!.GetValue<string>())));
        return o["type"] switch
        {
            JsonArray types => Union(types.Select(t => Primitive(t!.GetValue<string>()))),
            JsonValue t when t.GetValue<string>() == "array" => ArrayOf(Type(o["items"]!)),
            JsonValue t when t.GetValue<string>() == "object" && o["properties"] is JsonObject => ObjectBody(o),
            JsonValue t when t.GetValue<string>() == "string" && o["pattern"] is JsonValue p => Pattern(p.GetValue<string>()),
            JsonValue t => Primitive(t.GetValue<string>()),
            _ => "unknown",
        };
    }

    /// <summary>The schema's only free-standing pattern is the category word; it reads as <c>"Any"</c>.</summary>
    private static string Pattern(string pattern) =>
        pattern == "^(?:[aA][nN][yY]|~|[nN][uU][lL][lL])$" ? "\"Any\"" : "string";

    /// <summary><c>allOf [clause type, required [key]]</c>: the clause type with its discriminator key present.</summary>
    private static string AllOf(JsonArray parts)
    {
        var types = new List<string>();
        var required = new List<string>();
        foreach (var part in parts)
        {
            if (part?["required"] is JsonArray keys)
                required.AddRange(keys.Select(k => k!.GetValue<string>()));
            else
                types.Add(Type(part!));
        }
        var core = string.Join(" & ", types);
        return required.Count == 0
            ? core
            : $"{core} & Required<Pick<{core}, {string.Join(" | ", required.Select(Literal))}>>";
    }

    private static string ObjectBody(JsonObject o)
    {
        var sb = new StringBuilder("{\n");
        foreach (var (key, value) in (JsonObject)o["properties"]!)
            sb.Append("  ").Append(PropertyKey(key)).Append("?: ").Append(Type(value!)).Append(";\n");
        return sb.Append('}').ToString();
    }

    private static string Primitive(string type) =>
        type switch
        {
            "integer" or "number" => "number",
            "string" => "string",
            "boolean" => "boolean",
            "null" => "null",
            _ => "unknown",
        };

    private static string Union(IEnumerable<string> members)
    {
        var distinct = members.Distinct().ToList();
        return distinct.Count == 1 ? distinct[0] : string.Join(" | ", distinct);
    }

    private static string ArrayOf(string element) =>
        element.Contains(' ') ? $"({element})[]" : $"{element}[]";

    private static string Literal(string value) =>
        "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    private static string PropertyKey(string key) => Identifier().IsMatch(key) ? key : Literal(key);

    [GeneratedRegex("^[A-Za-z_$][A-Za-z0-9_$]*$")]
    private static partial Regex Identifier();
}
